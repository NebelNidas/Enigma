#!/usr/bin/env bash
set -euo pipefail

usage() {
	cat <<'USAGE'
Usage: enigma-llm-plugin/evaluation/run-model-benchmark.sh <model-id> [date-tag]

Runs the fixed JSONL evaluation, the owner-vs-graph context comparison, and
summary printing for the currently loaded OpenAI-compatible model endpoint.

Optional environment:
  ENIGMA_LLM_MODEL          Default: <model-id>
  ENIGMA_LLM_BASE_URL      Default: http://127.0.0.1:1234/v1
  ENIGMA_LLM_API_KEY       Optional bearer token
  BENCHMARK_HARDWARE       Default: unknown
  BENCHMARK_QUANTIZATION   Default: unknown
  BENCHMARK_CONTEXT_TOKENS Default: unknown
  BENCHMARK_GPU_OFFLOAD    Default: unknown
  ENIGMA_LLM_BATCH_PARALLELISM Default: 2
  JAVA_HOME                Default: /usr/lib/jvm/java-17-openjdk
  GRADLE_USER_HOME         Default: <repo>/.gradle

Example:
  BENCHMARK_HARDWARE="RX 9060 XT 16 GB / LM Studio" \
  BENCHMARK_QUANTIZATION=Q5_K_M \
  BENCHMARK_CONTEXT_TOKENS=4096 \
  ENIGMA_LLM_MODEL=qwen2.5-coder-14b-q5km \
    enigma-llm-plugin/evaluation/run-model-benchmark.sh qwen2.5-coder-14b-q5km
USAGE
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
	usage
	exit 0
fi

if [[ $# -lt 1 || $# -gt 2 ]]; then
	usage >&2
	exit 2
fi

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"
model_id="$1"
date_tag="${2:-$(date +%F)}"

export JAVA_HOME="${JAVA_HOME:-/usr/lib/jvm/java-17-openjdk}"
export PATH="$JAVA_HOME/bin:$PATH"
export GRADLE_USER_HOME="${GRADLE_USER_HOME:-$repo_root/.gradle}"
export ENIGMA_LLM_BASE_URL="${ENIGMA_LLM_BASE_URL:-http://127.0.0.1:1234/v1}"
export ENIGMA_LLM_MODEL="${ENIGMA_LLM_MODEL:-$model_id}"
export ENIGMA_LLM_BATCH_PARALLELISM="${ENIGMA_LLM_BATCH_PARALLELISM:-2}"

benchmark_hardware="${BENCHMARK_HARDWARE:-unknown}"
benchmark_quantization="${BENCHMARK_QUANTIZATION:-unknown}"
benchmark_context_tokens="${BENCHMARK_CONTEXT_TOKENS:-unknown}"
benchmark_gpu_offload="${BENCHMARK_GPU_OFFLOAD:-unknown}"

sample_result="enigma-llm-plugin/evaluation/results/${model_id}-${date_tag}.jsonl"
context_result="enigma-llm-plugin/evaluation/results/context-backend-comparison-${model_id}-${date_tag}.jsonl"
summary_log="enigma-llm-plugin/evaluation/results/${model_id}-${date_tag}.summary.txt"
tsv_path="enigma-llm-plugin/evaluation/model-benchmark-runs.tsv"

cd "$repo_root"
mkdir -p enigma-llm-plugin/evaluation/results

{
	echo "# $model_id"
	echo "date=$date_tag"
	echo "base_url=$ENIGMA_LLM_BASE_URL"
	echo
	echo "## Sample evaluation"
	./gradlew :enigma-llm-plugin:runEvaluation -Pout="$sample_result"
	echo
	./gradlew :enigma-llm-plugin:summarizeEvaluation -Presults="$sample_result"
	echo
	echo "## Context backend comparison"
	./gradlew :enigma-llm-plugin:compareContextBackends -Pout="$context_result"
	echo
	./gradlew :enigma-llm-plugin:summarizeEvaluation -Presults="$context_result"
	echo
	echo "sample_result=$sample_result"
	echo "context_result=$context_result"
} | tee "$summary_log"

extract_summary_field() {
	local line="$1"
	local field="$2"
	printf '%s\n' "$line" | sed -E "s/.*${field}=([^ ]+).*/\\1/"
}

tsv_escape() {
	printf '%s' "$1" | tr '\t\r\n' '   '
}

append_tsv_row() {
	local run_id="$1"
	local task="$2"
	local result_path="$3"
	local total="$4"
	local accepted="$5"
	local exact="$6"
	local usable="$7"
	local failed="$8"
	local avg_latency="$9"
	local notes="${10}"

	printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
		"$(tsv_escape "$run_id")" \
		"$(tsv_escape "$date_tag")" \
		"$(tsv_escape "$benchmark_hardware")" \
		"$(tsv_escape "$ENIGMA_LLM_BASE_URL")" \
		"$(tsv_escape "$ENIGMA_LLM_MODEL")" \
		"$(tsv_escape "$benchmark_quantization")" \
		"$(tsv_escape "$benchmark_context_tokens")" \
		"$(tsv_escape "$benchmark_gpu_offload")" \
		"$(tsv_escape "$ENIGMA_LLM_BATCH_PARALLELISM")" \
		"$(tsv_escape "$task")" \
		"$(tsv_escape "${result_path#enigma-llm-plugin/}")" \
		"$(tsv_escape "$total")" \
		"$(tsv_escape "$accepted")" \
		"$(tsv_escape "$exact")" \
		"$(tsv_escape "$usable")" \
		"$(tsv_escape "$failed")" \
		"$(tsv_escape "$avg_latency")" \
		"$(tsv_escape "$notes")" >> "$tsv_path"
}

sample_summary="$(grep '^all:' "$summary_log" | tail -1 || true)"
owner_summary="$(grep '^owner:' "$summary_log" | tail -1 || true)"
graph_summary="$(grep '^graph:' "$summary_log" | tail -1 || true)"

if [[ -n "$sample_summary" ]]; then
	append_tsv_row \
		"${model_id}-sample-${date_tag}" \
		"runEvaluation" \
		"$sample_result" \
		"$(extract_summary_field "$sample_summary" "total")" \
		"$(extract_summary_field "$sample_summary" "accepted")" \
		"$(extract_summary_field "$sample_summary" "exact")" \
		"$(extract_summary_field "$sample_summary" "usable")" \
		"$(extract_summary_field "$sample_summary" "failed")" \
		"$(extract_summary_field "$sample_summary" "avgLatencyMs")" \
		"Generated by run-model-benchmark.sh"
fi

if [[ -n "$owner_summary" && -n "$graph_summary" ]]; then
	owner_total="$(extract_summary_field "$owner_summary" "total")"
	graph_total="$(extract_summary_field "$graph_summary" "total")"
	owner_accepted="$(extract_summary_field "$owner_summary" "accepted")"
	graph_accepted="$(extract_summary_field "$graph_summary" "accepted")"
	owner_exact="$(extract_summary_field "$owner_summary" "exact")"
	graph_exact="$(extract_summary_field "$graph_summary" "exact")"
	owner_usable="$(extract_summary_field "$owner_summary" "usable")"
	graph_usable="$(extract_summary_field "$graph_summary" "usable")"
	owner_failed="$(extract_summary_field "$owner_summary" "failed")"
	graph_failed="$(extract_summary_field "$graph_summary" "failed")"
	owner_avg="$(extract_summary_field "$owner_summary" "avgLatencyMs")"
	graph_avg="$(extract_summary_field "$graph_summary" "avgLatencyMs")"
	context_total=$((owner_total + graph_total))
	context_accepted=$((owner_accepted + graph_accepted))
	context_exact=$((owner_exact + graph_exact))
	context_usable=$((owner_usable + graph_usable))
	context_failed=$((owner_failed + graph_failed))
	context_avg="$(awk -v owner_total="$owner_total" -v owner_avg="$owner_avg" -v graph_total="$graph_total" -v graph_avg="$graph_avg" 'BEGIN { printf "%.1f", ((owner_total * owner_avg) + (graph_total * graph_avg)) / (owner_total + graph_total) }')"
	append_tsv_row \
		"${model_id}-context-${date_tag}" \
		"compareContextBackends" \
		"$context_result" \
		"$context_total" \
		"$context_accepted" \
		"$context_exact" \
		"$context_usable" \
		"$context_failed" \
		"$context_avg" \
		"Owner: ${owner_usable} usable; graph: ${graph_usable} usable. Generated by run-model-benchmark.sh"
fi

echo "Wrote summary: $summary_log"
echo "Appended TSV rows: $tsv_path"
