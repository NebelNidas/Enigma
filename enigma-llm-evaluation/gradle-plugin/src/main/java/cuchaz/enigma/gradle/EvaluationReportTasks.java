package cuchaz.enigma.gradle;

import static cuchaz.enigma.gradle.EvaluationGradleSupport.VERIFICATION_GROUP;
import static cuchaz.enigma.gradle.EvaluationGradleSupport.booleanProperty;
import static cuchaz.enigma.gradle.EvaluationGradleSupport.evaluationScript;
import static cuchaz.enigma.gradle.EvaluationGradleSupport.optionalFileProperty;
import static cuchaz.enigma.gradle.EvaluationGradleSupport.property;
import static cuchaz.enigma.gradle.EvaluationGradleSupport.pythonExecutable;

import java.io.File;
import java.util.ArrayList;
import java.util.List;

import org.gradle.api.Project;
import org.gradle.api.tasks.Exec;

final class EvaluationReportTasks {
	private EvaluationReportTasks() {
	}

	static void register(Project project) {
		registerScriptCheck(project);
		List<String> reportTasks = new ArrayList<>();
		registerReportTask(project, reportTasks, "writeMainBenchmarkReport", "main-benchmark",
				"Writes the local/main benchmark aggregate report without live model calls.");
		registerReportTask(project, reportTasks, "writeCommercialBenchmarkReport", "commercial-benchmark",
				"Writes the commercial benchmark aggregate report without live model calls.");
		registerReportTask(project, reportTasks, "writeBackendMatrixReports", "backend-matrix",
				"Writes owner/graph backend matrix reports without live model calls.");
		registerReportTask(project, reportTasks, "writeSemanticJudgeV2Report", "semantic-v2",
				"Writes the semantic-judge v2 adoption report from committed verdict artifacts.");
		registerReportTask(project, reportTasks, "writeReferenceAblationReport", "reference-ablation",
				"Writes the reference-ablation full-pool report from committed verdict artifacts.");
		registerReportTask(project, reportTasks, "writeHypoNearMissReport", "hypo-nearmiss",
				"Writes the Hypo near-miss report from committed raw outputs and verdict artifacts.");
		registerReportTask(project, reportTasks, "writeFixedJsonlSummaries", "fixed-jsonl",
				"Summarizes committed fixed JSONL smoke/context outputs without live model calls.");
		registerReportTask(project, reportTasks, "collectReportOnlyArtifacts", "report-only",
				"Collects committed historical report-only artifacts that are not regenerated by the offline replay tasks.");

		project.getTasks().register("writeEvaluationReports", task -> {
			task.setGroup(VERIFICATION_GROUP);
			task.setDescription("Runs every offline evaluation report task without live model calls.");
			task.dependsOn(reportTasks);
		});
	}

	private static void registerScriptCheck(Project project) {
		project.getTasks().register("checkEvaluationAnalysisScripts", Exec.class, task -> {
			task.setGroup(VERIFICATION_GROUP);
			task.setDescription("Syntax-checks committed Python evaluation analysis/report scripts.");

			List<File> scripts = List.of(
					evaluationScript(project, "aggregate_results.py"),
					evaluationScript(project, "analyze_backend_matrix.py"),
					evaluationScript(project, "compare_frontier_semantic_judges.py"),
					evaluationScript(project, "prepare_codex_prompt_batches.py"),
					evaluationScript(project, "write_evaluation_reports.py"),
					evaluationScript(project, "run_codex_prompt_batch.py"),
					evaluationScript(project, "run_fable_prompt_batch.py"),
					evaluationScript(project, "run_frontier_grok_semantic_judge.py"),
					evaluationScript(project, "run_frontier_semantic_judge.py"),
					evaluationScript(project, "score_prompt_batch.py"),
					evaluationScript(project, "score_frontier_runs.py"),
					evaluationScript(project, "summarize_frontier_semantic_judge.py"),
					evaluationScript(project, "verify_prompt_pairing.py"),
					evaluationScript(project, "semantic-judge/agg.py"),
					evaluationScript(project, "semantic-judge/agg_v2.py"),
					evaluationScript(project, "semantic-judge/ablfull_combine.py"),
					evaluationScript(project, "semantic-judge/build_ablation_full.py"),
					evaluationScript(project, "semantic-judge/hypo-nearmiss-2026-07-10/agg_hypo.py"));

			List<String> commandLine = new ArrayList<>();
			commandLine.add(pythonExecutable(project));
			commandLine.add("-m");
			commandLine.add("py_compile");
			scripts.stream()
					.filter(File::exists)
					.map(File::getPath)
					.forEach(commandLine::add);
			task.commandLine(commandLine);
		});
	}

	private static void registerReportTask(Project project, List<String> reportTasks, String taskName, String mode, String taskDescription) {
		reportTasks.add(taskName);
		project.getTasks().register(taskName, Exec.class, task -> {
			task.setGroup(VERIFICATION_GROUP);
			task.setDescription(taskDescription);
			task.dependsOn("checkEvaluationAnalysisScripts");

			task.commandLine(
					pythonExecutable(project),
					evaluationScript(project, "write_evaluation_reports.py").getPath(),
					"--only", mode,
					"--resamples", property(project, "reportResamples", "5000"));

			if (project.hasProperty("reportOut")) {
				task.args("--out", optionalFileProperty(project, "reportOut").getPath());
			}

			if (booleanProperty(project, "reportOverwrite")) {
				task.args("--overwrite");
			}

			if (booleanProperty(project, "reportDryRun")) {
				task.args("--dry-run");
			}
		});
	}
}
